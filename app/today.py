# app/today.py
"""「今天是几号」的唯一来源。

模型无从自知当前日期，只会拿训练截止时间当「现在」——问「未来 2 年」它就按旧年份起算，
搜出来的是过去的资料。所以每条会用到时间的提示词都得注入当前日期。

之所以单独成模块：这件事原先有两份实现且已经漂移——chat.py 按北京时间，executor.py 用
date.today()（服务器本地时区）。同一轮对话里两处说的「今天」可能差一天，跨时区部署时必然
不一致，而且没有任何报错。三处各写一遍只会继续漂，故收敛到这里。

时区固定北京：用户与内容都在国内，服务器时区随部署环境变化，不能当基准。
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone

CN_TZ = timezone(timedelta(hours=8))


def today_cn() -> datetime:
    """当前北京时间。"""
    return datetime.now(CN_TZ)


def today_iso() -> str:
    """YYYY-MM-DD（北京时间）。给提示词里只需要日期的地方用。"""
    return f"{today_cn():%Y-%m-%d}"


def today_guide() -> str:
    """完整的日期基准段落，供各类系统提示词拼接。

    措辞点明「不要沿用训练数据中的年份」：只给一个日期，模型仍可能按旧年份做区间推算
    （实测：2026 年问「未来 2 年」，规划器写出「2025-2026」这种已经过去的区间）。
    """
    return (f"\n\n【当前日期】今天是 {today_cn():%Y 年 %m 月 %d 日}（北京时间）。"
            "凡涉及「今年/去年/未来 N 年/最近/最新」等与时间相关的推算或表述，"
            "一律以此日期为当前时间基准，不要沿用训练数据中的年份。"
            "据此展开的年份区间必须从今年起算，不要写出已经过去的年份。")
